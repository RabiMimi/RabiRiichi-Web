#!/usr/bin/env python3
"""Draw the universal wildcard's UNO-inspired four-colour oval as an SVG.

Bold, flat quadrants and a dark outline keep the symbol legible on river tiles
and result badges. The white 700x933 canvas matches the other tile textures.
Explicit dimensions also keep browsers from rasterising it at 300x150.

Usage:  python3 tools/wildcard-face.py [out.svg]
        (default: public/assets/hand_tiles/wildcard.svg)
"""

import pathlib
import sys

WIDTH, HEIGHT = 700, 933
CX, CY = 350, 466
RX, RY = 222, 324

# Clockwise from the upper-left quadrant, in the oval's local coordinates.
QUADRANTS = [
    ("#ed1c24", (-RX, 0), (0, -RY)),
    ("#0878d1", (0, -RY), (RX, 0)),
    ("#18a849", (RX, 0), (0, RY)),
    ("#ffcc00", (0, RY), (-RX, 0)),
]


def render():
    quadrants = [
        f'<path d="M0 0 L{start[0]} {start[1]} '
        f'A{RX} {RY} 0 0 1 {end[0]} {end[1]}Z" fill="{colour}"/>'
        for colour, start, end in QUADRANTS
    ]
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" '
            f'height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">',
            "<!-- Universal wildcard tile face. Generated by "
            "tools/wildcard-face.py; edit that, not this file. -->",
            f'<rect width="{WIDTH}" height="{HEIGHT}" fill="#ffffff"/>',
            f'<g transform="translate({CX} {CY}) rotate(28)">',
            *quadrants,
            # White dividers separate the colours even at small display sizes.
            f'<path d="M{-RX} 0H{RX} M0 {-RY}V{RY}" '
            'fill="none" stroke="#ffffff" stroke-width="14"/>',
            f'<ellipse rx="{RX}" ry="{RY}" fill="none" '
            'stroke="#202124" stroke-width="22"/>',
            "</g>",
            "</svg>",
            "",
        ]
    )


def main():
    default = pathlib.Path(__file__).parent.parent / "public/assets/hand_tiles/wildcard.svg"
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
    out.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
