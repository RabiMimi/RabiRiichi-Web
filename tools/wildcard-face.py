#!/usr/bin/env python3
"""Draw the universal wildcard's tile face as an SVG.

The face is a faceted rainbow star: an axis-aligned four-point star in front of
a diagonal one, each point split into a lit and a shaded facet. Hues run round
the colour wheel, so the tile reads as "any suit" and stays recognisable at the
few pixels a river tile gets.

The canvas matches the copied JPG faces (700x933, white ground), so the texture
maps onto the tile mesh exactly like them. The root keeps explicit width and
height because some browsers rasterise an SVG texture at 300x150 without them.

Usage:  python3 tools/wildcard-face.py [out.svg]
        (default: public/assets/hand_tiles/wildcard.svg)
"""

import pathlib
import sys

WIDTH, HEIGHT = 700, 933
CX, CY = 350, 466
OUTLINE = "#3a2466"

# (light, base, dark) per compass point, clockwise from north.
HUES = [
    ("#ff8fa3", "#ff2e55", "#c2002e"),  # N  red
    ("#ffc27a", "#ff8a1f", "#d35f00"),  # NE orange
    ("#fff08a", "#ffd21f", "#d9a400"),  # E  yellow
    ("#9ff0c2", "#22c96e", "#0f8f4a"),  # SE green
    ("#9ce6ff", "#1fb8f2", "#0a7fb3"),  # S  cyan
    ("#a9bdff", "#3b63f5", "#2234b8"),  # SW blue
    ("#cfadff", "#8a45f5", "#5d1fc0"),  # W  violet
    ("#ffaee9", "#f23cc0", "#b3178a"),  # NW magenta
]

# The axis star is taller than wide to fill the portrait tile.
AXIS_TIPS = {0: (CX, 96), 2: (632, CY), 4: (CX, 836), 6: (68, CY)}
AXIS_WAIST = 74  # inner corners sit on the diagonals, this far from centre
DIAGONAL_TIPS = {1: (566, 214), 3: (566, 718), 5: (134, 718), 7: (134, 214)}
DIAGONAL_WAIST = 100  # inner corners sit on the axes, this far from centre


def axis_corners(point):
    """The two inner corners flanking an axis point, clockwise."""
    w = AXIS_WAIST
    nw, ne = (CX - w, CY - w), (CX + w, CY - w)
    se, sw = (CX + w, CY + w), (CX - w, CY + w)
    return {0: (nw, ne), 2: (ne, se), 4: (se, sw), 6: (sw, nw)}[point]


def diagonal_corners(point):
    """The two inner corners flanking a diagonal point, clockwise."""
    w = DIAGONAL_WAIST
    n, e, s, west = (CX, CY - w), (CX + w, CY), (CX, CY + w), (CX - w, CY)
    return {1: (n, e), 3: (e, s), 5: (s, west), 7: (west, n)}[point]


def xy(p):
    return f"{p[0]},{p[1]}"


def gradient(gid, tip, stops):
    """A gradient glowing out of the centre towards a point's tip."""
    stop_xml = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in stops)
    return (
        f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" '
        f'x1="{CX}" y1="{CY}" x2="{tip[0]}" y2="{tip[1]}">{stop_xml}'
        "</linearGradient>"
    )


def star(prefix, tips, corners):
    """Gradients and facet polygons for one star, plus its outline points."""
    defs, facets, outline = [], [], []
    for point, tip in sorted(tips.items()):
        light, base, dark = HUES[point]
        left, right = corners(point)
        lit, shade = f"{prefix}{point}l", f"{prefix}{point}d"
        defs.append(gradient(lit, tip, [(0, "#ffffff"), (0.35, light), (1, base)]))
        defs.append(gradient(shade, tip, [(0, light), (0.55, base), (1, dark)]))
        centre = (CX, CY)
        facets.append(
            f'<polygon points="{xy(centre)} {xy(left)} {xy(tip)}" fill="url(#{lit})"/>'
        )
        facets.append(
            f'<polygon points="{xy(centre)} {xy(tip)} {xy(right)}" fill="url(#{shade})"/>'
        )
        outline += [left, tip]
    return defs, facets, " ".join(xy(p) for p in outline)


def sparkle(x, y, r, fill):
    """A small curved four-point twinkle."""
    t = round(r * 0.22, 2)
    return (
        f'<path d="M{x} {y - r} Q{x + t} {y - t} {x + r} {y} '
        f"Q{x + t} {y + t} {x} {y + r} Q{x - t} {y + t} {x - r} {y} "
        f'Q{x - t} {y - t} {x} {y - r}Z" fill="{fill}"/>'
    )


def render():
    diag_defs, diag_facets, diag_outline = star("g", DIAGONAL_TIPS, diagonal_corners)
    axis_defs, axis_facets, axis_outline = star("m", AXIS_TIPS, axis_corners)
    facet_group = '<g stroke="#ffffff" stroke-width="3" stroke-linejoin="round">{}</g>'
    outline = (
        '<polygon points="{}" fill="none" stroke="' + OUTLINE + '" '
        'stroke-width="{}" stroke-linejoin="round"/>'
    )
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" '
            f'height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">',
            "<!-- Universal wildcard tile face. Generated by "
            "tools/wildcard-face.py; edit that, not this file. -->",
            "<defs>",
            f'<radialGradient id="halo" cx="{CX}" cy="{CY}" r="330" '
            'gradientUnits="userSpaceOnUse">'
            '<stop offset="0" stop-color="#fff6c8" stop-opacity="0.95"/>'
            '<stop offset="0.55" stop-color="#ffe3f4" stop-opacity="0.55"/>'
            '<stop offset="1" stop-color="#ffffff" stop-opacity="0"/>'
            "</radialGradient>",
            f'<radialGradient id="core" cx="{CX}" cy="{CY}" r="62" '
            'gradientUnits="userSpaceOnUse">'
            '<stop offset="0" stop-color="#ffffff"/>'
            '<stop offset="0.6" stop-color="#ffffff" stop-opacity="0.85"/>'
            '<stop offset="1" stop-color="#ffffff" stop-opacity="0"/>'
            "</radialGradient>",
            "".join(diag_defs + axis_defs),
            "</defs>",
            f'<rect width="{WIDTH}" height="{HEIGHT}" fill="#ffffff"/>',
            f'<ellipse cx="{CX}" cy="{CY}" rx="330" ry="400" fill="url(#halo)"/>',
            facet_group.format("".join(diag_facets)),
            outline.format(diag_outline, 7),
            facet_group.format("".join(axis_facets)),
            outline.format(axis_outline, 9),
            f'<circle cx="{CX}" cy="{CY}" r="62" fill="url(#core)"/>',
            sparkle(CX, CY, 46, "#ffffff"),
            sparkle(150, 120, 34, "#ffc21f"),
            sparkle(575, 830, 30, "#ff4dc4"),
            sparkle(600, 120, 20, "#1fb8f2"),
            sparkle(108, 840, 18, "#22c96e"),
            "</svg>",
            "",
        ]
    )


def main():
    default = pathlib.Path(__file__).parent.parent / "public/assets/hand_tiles/wildcard.svg"
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
    out.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
